#!/usr/bin/env python3
"""Write a YOLO data.yaml that trains/validates on SeaShips + Open
Images' "Boat" class + the Roboflow "Sailboat detector" dataset
together, to fix the catastrophic forgetting a SeaShips-only fine-tune
causes on real sailboats (see README) -- mixing in visually diverse
and sailing-specific data instead of fine-tuning on commercial
shipping alone.

Requires all three samples to already exist:
    python scripts/fetch_seaships_sample.py --n 1500
    python scripts/fetch_openimages_boats_sample.py --n 500
    python scripts/fetch_roboflow_sailboat_sample.py

Usage:
    python scripts/make_combined_boat_dataset.py
"""
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DATASETS = REPO_ROOT / "data" / "datasets"
SEASHIPS = DATASETS / "seaships_sample"
OPENIMAGES = DATASETS / "openimages_boats_sample"
ROBOFLOW_SAILBOAT = DATASETS / "roboflow_sailboat_sample"
OUT_DIR = DATASETS / "combined"


def main():
    sources = [
        ("SeaShips", SEASHIPS, SEASHIPS / "images" / "train", SEASHIPS / "images" / "val"),
        ("Open Images boats", OPENIMAGES,
         OPENIMAGES / "images" / "train", OPENIMAGES / "images" / "val"),
        ("Roboflow Sailboat detector", ROBOFLOW_SAILBOAT,
         ROBOFLOW_SAILBOAT / "train" / "images", ROBOFLOW_SAILBOAT / "valid" / "images"),
    ]
    for name, path, _, _ in sources:
        if not path.exists():
            raise SystemExit(
                f"{name} sample not found at {path} -- fetch it first (see module docstring)"
            )

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    data_yaml = OUT_DIR / "data.yaml"
    train_lines = "\n".join(f"  - {train}" for _, _, train, _ in sources)
    val_lines = "\n".join(f"  - {val}" for _, _, _, val in sources)
    data_yaml.write_text(
        "# SeaShips (commercial shipping) + Open Images \"Boat\" class\n"
        "# (varied: jet skis, dinghies, yachts, canoes) + Roboflow\n"
        "# Sailboat detector (sailing-specific) -- generated by\n"
        "# make_combined_boat_dataset.py\n"
        "train:\n"
        f"{train_lines}\n"
        "val:\n"
        f"{val_lines}\n"
        "names:\n"
        "  0: boat\n"
    )
    print(f"Wrote {data_yaml}")


if __name__ == "__main__":
    main()
