#!/usr/bin/env python3
"""Write a YOLO data.yaml that trains/validates on SeaShips + Open
Images' "Boat" class together, to fix the catastrophic forgetting a
SeaShips-only fine-tune causes on real sailboats (see README) -- mixing
in a visually diverse generic-boat set instead of fine-tuning on
commercial shipping alone.

Requires both samples to already exist:
    python scripts/fetch_seaships_sample.py --n 1500
    python scripts/fetch_openimages_boats_sample.py --n 500

Usage:
    python scripts/make_combined_boat_dataset.py
"""
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DATASETS = REPO_ROOT / "data" / "datasets"
SEASHIPS = DATASETS / "seaships_sample"
OPENIMAGES = DATASETS / "openimages_boats_sample"
OUT_DIR = DATASETS / "combined"


def main():
    for name, path in [("SeaShips", SEASHIPS), ("Open Images boats", OPENIMAGES)]:
        if not path.exists():
            raise SystemExit(
                f"{name} sample not found at {path} -- fetch it first (see module docstring)"
            )

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    data_yaml = OUT_DIR / "data.yaml"
    data_yaml.write_text(
        "# Combined SeaShips (commercial shipping, narrow domain) + Open\n"
        "# Images \"Boat\" class (varied: jet skis, dinghies, yachts,\n"
        "# canoes, etc.) -- generated by make_combined_boat_dataset.py\n"
        "train:\n"
        f"  - {SEASHIPS / 'images' / 'train'}\n"
        f"  - {OPENIMAGES / 'images' / 'train'}\n"
        "val:\n"
        f"  - {SEASHIPS / 'images' / 'val'}\n"
        f"  - {OPENIMAGES / 'images' / 'val'}\n"
        "names:\n"
        "  0: boat\n"
    )
    print(f"Wrote {data_yaml}")


if __name__ == "__main__":
    main()
